function hash32(value) {
  let h = 2166136261;
  for (const ch of String(value)) {
    h ^= ch.charCodeAt(0);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
function choose(values, key) {
  if (!values.length) throw new Error("Empty choice list: " + key);
  return values[hash32(key) % values.length];
}
function dateRu(value) {
  const [y, m, d] = String(value || "").slice(0, 10).split("-");
  return y && m && d ? [d, m, y].join(".") : "дата не указана";
}
function plusDays(value, days) {
  const d = new Date(String(value).slice(0, 10) + "T12:00:00Z");
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}
function topicOf(subject) {
  const s = String(subject || "");
  if (s.includes("—")) return s.split("—").slice(1).join("—").trim();
  return s.replace(/^Внутреннее обсуждение:\s*/i, "").trim();
}
function capitalise(value) {
  const s = String(value || "").trim();
  return s ? s[0].toLocaleUpperCase("ru-RU") + s.slice(1) : s;
}
