export function diversifyActivities(pages, contactRows, seed = SEED) {
  const contacts = new Map(contactRows.map(c => [String(c.id), c]));
  const rows = pages.flatMap(p => p.result);
  const idsBefore = rows.map(r => r.ID);
  const communicationsBefore = rows.map(r => JSON.stringify(r.COMMUNICATIONS || []));
  let rewritten = 0;
  for (const activity of rows) {
    if (String(activity.TYPE_ID) !== "4") continue;
    activity.DESCRIPTION = String(activity.SUBJECT || "").startsWith("Внутреннее обсуждение:")
      ? makeInternal(activity, contacts, seed)
      : makeExternal(activity, contacts, seed);
    if (!activity.DESCRIPTION.trim()) throw new Error("Empty DESCRIPTION for activity " + activity.ID);
    rewritten++;
  }
  if (rewritten !== 324) throw new Error("Expected 324 email activities, got " + rewritten);
  if (rows.length !== 630) throw new Error("Expected 630 activities, got " + rows.length);
  if (rows.some((r, i) => r.ID !== idsBefore[i])) throw new Error("Activity IDs changed");
  if (rows.some((r, i) => JSON.stringify(r.COMMUNICATIONS || []) !== communicationsBefore[i])) {
    throw new Error("COMMUNICATIONS changed");
  }
  return { rows, rewritten };
}

