function stableIndex(key, length) {
  let hash = 2166136261;
  for (const ch of key) hash = Math.imul(hash ^ ch.charCodeAt(0), 16777619);
  return (hash >>> 0) % length;
}

export function buildCommunicationContext(event, seed) {
  const options = scopeDetails[event.scope] || scopeDetails.commercial;
  const detail = options[stableIndex(String(seed) + ":" + event.id + ":scope-context", options.length)];
  const opener = eventOpeners[event.type] || "В рамках сделки";
  return opener + ": " + detail.charAt(0).toLowerCase() + detail.slice(1);
}
