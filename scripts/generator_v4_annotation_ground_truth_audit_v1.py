"""GEN-010.11B: compare frozen preliminary annotations with synthetic Ground Truth.

This evaluator accepts the corrected-v2 annotation JSON and the restricted answer key.
It intentionally does not calculate Cohen's kappa: there is only one annotation stream.
"""
from __future__ import annotations
import argparse, json
from collections import Counter, defaultdict
from pathlib import Path
from statistics import mean, median

CLASSES = (
    "request_information", "delegate", "complete_task", "review", "recommend",
    "object", "revise", "unit_approval", "approve", "reject", "close"
)
PREDICTIONS = CLASSES + ("unclear",)
RATINGS = ("event_clarity_1_to_5", "naturalness_1_to_5", "factual_support_1_to_5")


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def annotation_map(payload):
    result = {}
    for row in payload.get("records", []):
        rid = row.get("review_id")
        if not rid or rid in result:
            raise ValueError(f"missing or duplicate annotation review_id: {rid!r}")
        ann = row.get("reviewer_llm_v2") or row.get("reviewer_1") or row
        label = ann.get("primary_event_type")
        if label not in PREDICTIONS:
            raise ValueError(f"invalid annotation label for {rid}: {label!r}")
        for field in RATINGS:
            v = ann.get(field)
            if v is not None and (not isinstance(v, int) or isinstance(v, bool) or not 1 <= v <= 5):
                raise ValueError(f"invalid {field} for {rid}: {v!r}")
        result[rid] = ann
    return result


def evaluate(annotations, answer_key):
    pred = annotation_map(annotations)
    key = {}
    for row in answer_key.get("records", []):
        rid = row.get("review_id")
        if not rid or rid in key:
            raise ValueError(f"missing or duplicate answer-key review_id: {rid!r}")
        if row.get("ground_truth_event_type") not in CLASSES:
            raise ValueError(f"invalid Ground Truth class for {rid}")
        key[rid] = row
    if len(key) != 220 or set(key) != set(pred):
        raise ValueError(f"expected exact 220-record ID match; annotations={len(pred)}, key={len(key)}")

    ids = sorted(key)
    y = [key[i]["ground_truth_event_type"] for i in ids]
    p = [pred[i]["primary_event_type"] for i in ids]
    matrix = {a: {b: 0 for b in PREDICTIONS} for a in CLASSES}
    for a, b in zip(y, p):
        matrix[a][b] += 1
    per_class = {}
    ps, rs, fs = [], [], []
    for label in CLASSES:
        tp = matrix[label][label]
        fp = sum(matrix[a][label] for a in CLASSES if a != label)
        fn = sum(matrix[label][b] for b in PREDICTIONS if b != label)
        support = sum(matrix[label].values())
        precision = tp / (tp + fp) if tp + fp else 0.0
        recall = tp / (tp + fn) if tp + fn else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        per_class[label] = {"support": support, "precision": round(precision,4),
                            "recall": round(recall,4), "f1": round(f1,4)}
        ps.append(precision); rs.append(recall); fs.append(f1)
    total = len(ids)
    correct = sum(a == b for a,b in zip(y,p))
    # Treat unclear as an explicit 12th predicted category for a second macro-F1 view.
    f1_unclear = 0.0
    if any(v == "unclear" for v in p):
        f1_unclear = 0.0
    by_channel = defaultdict(lambda: {"n":0,"correct":0})
    for rid, a, b in zip(ids,y,p):
        ch = key[rid].get("channel","unknown")
        by_channel[ch]["n"] += 1
        by_channel[ch]["correct"] += int(a == b)
    ratings = {}
    for field in RATINGS:
        vals = [pred[i][field] for i in ids if pred[i].get(field) is not None]
        ratings[field] = {"n":len(vals), "mean":round(mean(vals),3) if vals else None,
                          "median":median(vals) if vals else None,
                          "distribution":dict(sorted(Counter(vals).items()))}
    unsupported = [pred[i].get("unsupported_claims",[]) for i in ids]
    return {
        "audit":"GEN-010.11B",
        "status":"COMPLETED_PRELIMINARY_AUTOMATED_BASELINE",
        "n":total,
        "annotation_provenance":{
            "source":"corrected-v2 scripted keyword/rule-assisted annotation",
            "is_true_llm_inference":False,
            "is_human_expert_review":False,
            "ground_truth_used_during_annotation":False,
            "note":"Earlier description as LLM-generated was inaccurate; the frozen annotation file was generated by deterministic Python rules."
        },
        "primary_metrics":{
            "accuracy":round(correct/total,4),
            "macro_precision_11_gt_classes":round(mean(ps),4),
            "macro_recall_11_gt_classes":round(mean(rs),4),
            "macro_f1_11_gt_classes":round(mean(fs),4),
            "macro_f1_12_classes_including_unclear":round((sum(fs)+f1_unclear)/12,4)
        },
        "per_class":per_class,
        "ground_truth_distribution":dict(sorted(Counter(y).items())),
        "predicted_distribution":dict(sorted(Counter(p).items())),
        "confusion_matrix_labels":list(CLASSES)+["unclear"],
        "confusion_matrix_actual_rows_predicted_columns":[[matrix[a][b] for b in PREDICTIONS] for a in CLASSES],
        "accuracy_by_channel":{ch:{"n":v["n"],"accuracy":round(v["correct"]/v["n"],4)} for ch,v in sorted(by_channel.items())},
        "ratings":ratings,
        "records_with_unsupported_claims":sum(bool(x) for x in unsupported),
        "unsupported_claim_items":sum(len(x) for x in unsupported),
        "limitations":[
            "This is a rule-assisted automated baseline, not an LLM expert assessment.",
            "The 220-record sample is balanced by Ground Truth class and is diagnostic, not prevalence-representative.",
            "Agreement with synthetic Ground Truth measures consistency with scenario labels, not real-world CRM validity.",
            "No Cohen's kappa is calculated because there are not two independent annotators.",
            "A true LLM assessment requires a fresh blinded annotation pass frozen before its answer key is opened."
        ]
    }


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--annotations",required=True)
    ap.add_argument("--answer-key",required=True)
    ap.add_argument("--output",default="gen01011b-report.json")
    args=ap.parse_args()
    report=evaluate(load(args.annotations),load(args.answer_key))
    Path(args.output).write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding="utf-8")
    print(json.dumps({"status":report["status"],"n":report["n"],"metrics":report["primary_metrics"]},ensure_ascii=False,indent=2))


if __name__=="__main__":
    main()
