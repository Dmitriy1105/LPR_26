  const mapping = readJson(resolve(sourceDir, "id_mapping.json"));
  const contacts = readJson(resolve(sourceDir, "contacts/page_001.json")).result.items;
  const contactById = new Map(contacts.map(c => [String(c.id), [c.name, c.lastName].filter(Boolean).join(" ")]));
  const roleById = new Map(contacts.map(c => [String(c.id), c.post || "представитель клиента"]));
  const exact = new Set();
  const emailEndings = new Set();
  const counts = { call: 0, email: 0, meeting: 0 };
  const outputManifest = structuredClone(manifest);

  for (const method of outputManifest.methods) {
    for (const page of method.pages) {
      const rel = page.file;
      const input = readJson(resolve(sourceDir, rel));
      if (method.key === "activities") {
        for (const activity of input.result) {
          const { type, ending } = transformActivity(activity, contactById, roleById);
          counts[type]++;
          if (type === "email") emailEndings.add(ending);
          const normalized = activity.DESCRIPTION.toLowerCase()
            .replace(/\b\d{2}\.\d{2}\.\d{4}\b/g, " date ")
            .replace(/[^\p{L}\p{N}]+/gu, " ").replace(/\s+/g, " ").trim();
          exact.add(normalized);
        }
      }
      writeJson(resolve(outputDir, rel), input);
    }
  }

  for (const rel of ["id_mapping.json", "errors/access_denied.json", "errors/insufficient_scope.json", "errors/invalid_credentials.json"]) {
    writeJson(resolve(outputDir, rel), readJson(resolve(sourceDir, rel)));
  }

  outputManifest.snapshotDate = "2026-11-23";
  outputManifest.generatorVersion = "3.2.3";
  outputManifest.parentGeneratorVersion = "3.2.2";
  outputManifest.datasetVersion = "v3.2.3";
  outputManifest.generationSeed = SEED;
  outputManifest.sourceBranch = "feature/synthetic-bank-v3.2.3-nlp-diversity";
  outputManifest.sourceDataset = "src/data/bitrix24_contract_v2";
  outputManifest.textGeneration = "activity_type_specific_opening_argument_and_closing_variants";
  outputManifest.recordCounts = { ...manifest.recordCounts };
